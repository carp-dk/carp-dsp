package carp.dsp.demo.eval

import carp.dsp.demo.io.DemoIo

/**
 * Dependency-drift eval.
 *
 * Demonstrates the failure mode CARP-DSP prevents: an unpinned analysis dependency silently
 * changing scientific outputs. The Use Case of walking-speed pipeline is run over every recording
 * in the mobgap LabExample dataset under several released versions of mobgap, holding the input
 * data and the pipeline code fixed so the library version is the only variable.
 *
 * Requires pixi on PATH (https://pixi.sh), the same tool CARP-DSP uses for the workflow env.
 *
 * Run from the demo menu (id: dependency-drift-eval):
 *   ./gradlew :carp.dsp.demo:run --args "run dependency-drift-eval"
 *
 * Writes eval_results/drift-per-datapoint.csv, drift-summary.{txt,csv}, drift-table.tex,
 * drift-numbers.tex and eval_results/fig-dependency-drift.{png,pdf}. First run is slow (pixi
 * solves one env per version); later runs reuse the cached envs under build/drift-pixi. With
 * -PpaperDir the numbers go to the paper's generated/ and the figure to its images/.
 */

fun main() {
    val projectRoot = DemoIo.projectRoot()
    val scriptsDir = projectRoot.resolve("src/jvmMain/resources/scripts/eval")
    val driver = scriptsDir.resolve("drift_experiment.py")
    val evalResults = projectRoot.resolve("eval_results").apply { mkdirs() }
    val figStem = evalResults.resolve("fig-dependency-drift")
    // Keep the pixi project (manifest, lock, envs) under build/ (git-ignored, removed by
    // `gradle clean`), never inside resources/ (it must not be packaged into the jar).
    val workDir = projectRoot.resolve("build/drift-pixi")

    if (!driver.exists()) {
        System.err.println("Drift driver not found at ${driver.absolutePath}")
        return
    }

    val python = detectPython()
    if (python == null) {
        System.err.println("No Python interpreter found (tried python3, python). Install Python to run this eval.")
        return
    }

    println("Running dependency-drift experiment (first run has pixi solve one env per mobgap version)...")
    val command = mutableListOf(
        python, driver.absolutePath,
        "--out", evalResults.absolutePath,
        "--fig", figStem.absolutePath,
        "--work-dir", workDir.absolutePath,
    )
    // Override the conda-forge Python pixi provisions for every env (default 3.11).
    System.getenv("CARP_DRIFT_PY_VERSION")?.takeIf { it.isNotBlank() }?.let {
        command += listOf("--py-version", it)
    }
    val process = ProcessBuilder(command).redirectErrorStream(true).start()
    process.inputStream.bufferedReader().forEachLine { println(it) }
    val code = process.waitFor()

    // A failed sweep must not leave old or partial numbers looking current.
    check(code == 0) { "Drift experiment exited with code $code; drift-numbers.tex and the figure were not updated." }
    val summary = evalResults.resolve("drift-summary.txt")
    if (summary.exists()) {
        println()
        println(summary.readText())
    }
    val numbers = evalResults.resolve("drift-numbers.tex")
        .apply { writeText(driftNumbers(evalResults.resolve("drift-summary.csv").readLines())) }
    DemoIo.publishToPaper(numbers, "generated/drift-numbers.tex")
    DemoIo.publishToPaper(evalResults.resolve("fig-dependency-drift.pdf"), "images/fig-dependency-drift.pdf")
    println("Wrote drift-per-datapoint.csv, drift-summary.{txt,csv}, drift-table.tex, drift-numbers.tex")
    println("and fig-dependency-drift.{png,pdf} to: ${evalResults.absolutePath}")
}

/** The pinned version the sweep compares against; must match BASELINE in drift_experiment.py. */
private const val DRIFT_BASELINE = "0.10.0"

/**
 * The numbers the paper quotes, as LaTeX macros: the first upgrade after the
 * baseline that changes any walking speed, how many recordings it changes, and the
 * mean (over all recordings) and largest change in mm/s.
 *
 * @param summaryCsv the lines of drift-summary.csv, header first, one row per
 *   version other than the baseline.
 */
internal fun driftNumbers(summaryCsv: List<String>): String {
    val header = summaryCsv.first().split(',')
    val rows = summaryCsv.drop(1).filter { it.isNotBlank() }.map { line ->
        header.zip(line.split(',')).toMap()
    }
    val byVersion = compareBy<String, List<Int>>(versionComparator) { v -> v.split('.').map(String::toInt) }
    val versions = (rows.map { it.getValue("version") } + DRIFT_BASELINE).sortedWith(byVersion)
    val upgrade = rows
        .filter { byVersion.compare(it.getValue("version"), DRIFT_BASELINE) > 0 && it.getValue("changed").toInt() > 0 }
        .minWithOrNull(compareBy(byVersion) { it.getValue("version") })
    checkNotNull(upgrade) { "No version after $DRIFT_BASELINE changes any recording." }

    fun minor(v: String) = v.split('.').take(2).joinToString(".")
    fun mm(key: String) = Math.round(upgrade.getValue(key).toDouble()).toString()
    return buildString {
        appendLine("% GENERATED by DriftEval - do not edit; run the dependency-drift-eval demo")
        fun macro(name: String, value: String) = appendLine("\\newcommand{\\$name}{$value}")
        macro("DriftVersions", versions.size.toString())
        macro("DriftFirstVersion", minor(versions.first()))
        macro("DriftLastVersion", minor(versions.last()))
        macro("DriftRecordings", upgrade.getValue("total"))
        macro("DriftBaseline", minor(DRIFT_BASELINE))
        macro("DriftUpgrade", minor(upgrade.getValue("version")))
        macro("DriftChanged", upgrade.getValue("changed"))
        macro("DriftMeanMmS", mm("mean_abs_mm"))
        macro("DriftMaxMmS", mm("max_abs_mm"))
    }
}

/** Orders dotted version numbers part by part: 0.9 before 0.10. */
private val versionComparator = Comparator<List<Int>> { a, b ->
    a.zip(b).map { (x, y) -> x.compareTo(y) }.firstOrNull { it != 0 } ?: a.size.compareTo(b.size)
}

/** First interpreter of [python3, python] that responds to --version. */
private fun detectPython(): String? =
    listOf("python3", "python").firstOrNull { exe ->
        @Suppress("BAN_KOTLIN_TRY_CATCH")
        try {
            ProcessBuilder(exe, "--version").redirectErrorStream(true).start().waitFor() == 0
        } catch (_: Exception) {
            false
        }
    }

