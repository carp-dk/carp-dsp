/**
 * EX2 eval: does the locked gait workflow give the same outputs on every platform?
 *
 * Runs `mobgap-gait-analysis.yaml` through CARP-DSP (prepare, provision from the lock
 * file, execute) and fingerprints every CSV the steps write (line endings normalised;
 * plots are left out, since fonts render differently). Each platform writes
 * `eval_results/gait-portability/<platform>.csv` and a copy of its CSVs; every run then
 * compares all platforms present, and for a file that differs reports the largest
 * difference between numeric cells.
 *
 *   ./gradlew :carp.dsp.demo:evalGaitPortabilityAll -PpaperDir=../carp-dsp-sys-paper
 *
 * runs it in a Linux container (Docker) and then on this machine. The macOS and other
 * runner results come from the `cross-os-evals` GitHub workflow; drop their folders in
 * `eval_results/gait-portability/` and run `evalGaitPortability -Pargs=compare`.
 */
fun main( args: Array<String> )
{
    val dir = DemoIo.evalResultsDir().resolve( "gait-portability" ).apply { mkdirs() }
    if ( args.firstOrNull() != "compare" ) runHere( dir )

    val comparison = comparePlatforms( dir )
    println( comparison.report )
    val numbers = DemoIo.evalResultsDir().resolve( "gait-portability-numbers.tex" )
    numbers.writeText(
        buildString {
            appendLine( "% GENERATED by GaitPortabilityEval - do not edit; run :carp.dsp.demo:evalGaitPortabilityAll" )
            fun macro( name: String, value: Any ) = appendLine( "\\newcommand{\\$name}{$value}" )
            macro( "GaitPortPlatforms", comparison.platforms.size )
            macro( "GaitPortPlatformNames", comparison.platforms.joinToString( ", " ) )
            macro( "GaitPortFiles", comparison.files )
            macro( "GaitPortIdentical", comparison.identical )
            macro( "GaitPortMaxAbsDiff", comparison.maxAbsDiff?.let { "%.1e".format( Locale.ROOT, it ) } ?: "0" )
        }
    )
    DemoIo.publishToPaper( numbers, "generated/gait-portability-numbers.tex" )
}

/** Runs the gait workflow on this machine and writes this platform's fingerprint and CSVs. */
private fun runHere( dir: File )
{
    val platform = "${System.getProperty( "os.name" )} ${System.getProperty( "os.arch" )}"
    val slug = platform.lowercase().replace( Regex( "[^a-z0-9]+" ), "-" ).trim( '-' )
    val work = DemoRun.freshResultsDir( DemoIo.projectRoot().resolve( "build/gait-portability" ).toPath() )
    val loaded = DemoRun.loadWorkflow( "workflows/mobgap-gait-analysis.yaml", work )
    val executor = WorkflowExecutor.filesystem( ClasspathStepLibrary(), work )
    val prepared = executor.prepare( loaded.source, loaded.descriptor )
    val runId = UUID.randomUUID()
    val runRoot = MobgapScripts.runRoot( work, prepared.plan, runId )
    MobgapScripts.stage( runRoot )

    println( "Gait portability: running the locked gait workflow on $platform..." )
    val report = executor.run( prepared, runId )
    check( report.status == ExecutionStatus.SUCCEEDED ) {
        "Gait run failed: " + report.issues.joinToString( "; " ) { it.message }
    }

    val csvs = runRoot.resolve( "steps" ).toFile().walkTopDown()
        .filter { it.isFile && it.extension == "csv" && it.parentFile.name == "outputs" }
        .associateBy { it.relativeTo( runRoot.resolve( "steps" ).toFile() ).invariantSeparatorsPath }
        .toSortedMap()
    val copy = dir.resolve( slug ).apply { deleteRecursively(); mkdirs() }
    csvs.forEach { ( rel, f ) -> copy.resolve( rel ).apply { parentFile.mkdirs() }.writeText( normalised( f ) ) }
    dir.resolve( "$slug.csv" ).writeText(
        buildString {
            appendLine( "platform,java,file,sha256" )
            csvs.forEach { ( rel, f ) -> appendLine( "$platform,${System.getProperty( "java.version" )},$rel,${sha256( normalised( f ) )}" ) }
        }
    )
    println( "Wrote ${csvs.size} output fingerprints for $platform" )
}

private data class GaitComparison(
    val platforms: List<String>,
    val files: Int,
    val identical: Int,
    val maxAbsDiff: Double?,
    val report: String
)

/** Compares every platform's fingerprints in [dir]; differing files get a numeric diff. */
private fun comparePlatforms( dir: File ): GaitComparison
{
    val fingerprints = dir.listFiles { f -> f.extension == "csv" }.orEmpty().sortedBy { it.name }.associate { f ->
        val rows = f.readLines().drop( 1 ).filter { it.isNotBlank() }.map { it.split( "," ) }
        f.nameWithoutExtension to ( rows.first()[0] to rows.associate { it[2] to it[3] } )
    }
    val names = fingerprints.values.map { it.first }
    val files = fingerprints.values.flatMap { it.second.keys }.toSortedSet()
    val differing = files.filter { file -> fingerprints.values.map { it.second[file] }.toSet().size > 1 }
    val diffs = differing.associateWith { file -> maxNumericDiff( fingerprints.keys.map { dir.resolve( it ).resolve( file ) } ) }
    val maxAbs = diffs.values.filterNotNull().maxOrNull()

    val report = buildString {
        appendLine( "=".repeat( 78 ) )
        appendLine( "Gait portability (EX2) - ${java.time.Instant.now()}" )
        appendLine( "Platforms: ${names.joinToString( ", " )}" )
        appendLine( "Output CSVs: ${files.size}; identical on every platform: ${files.size - differing.size}" )
        diffs.forEach { ( file, d ) ->
            appendLine( "  differs: $file  (largest numeric difference: ${d?.let { "%.3e".format( Locale.ROOT, it ) } ?: "not numeric"})" )
        }
        appendLine( "=".repeat( 78 ) )
    }
    return GaitComparison( names, files.size, files.size - differing.size, maxAbs, report )
}

/** Largest absolute difference between numeric cells at the same position, or null if none compare. */
private fun maxNumericDiff( copies: List<File> ): Double?
{
    val tables = copies.filter { it.isFile }.map { f -> f.readLines().map { it.split( "," ) } }
    if ( tables.size < 2 ) return null
    var max: Double? = null
    val reference = tables.first()
    tables.drop( 1 ).forEach { other ->
        reference.zip( other ).forEach { ( a, b ) ->
            a.zip( b ).forEach { ( x, y ) ->
                val dx = x.toDoubleOrNull()
                val dy = y.toDoubleOrNull()
                if ( dx != null && dy != null ) max = maxOf( max ?: 0.0, abs( dx - dy ) )
            }
        }
    }
    return max
}

private fun normalised( f: File ): String = f.readText().replace( "\r\n", "\n" )

private fun sha256( text: String ): String =
    MessageDigest.getInstance( "SHA-256" ).digest( text.toByteArray() ).joinToString( "" ) { "%02x".format( it ) }
