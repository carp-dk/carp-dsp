/**
 * AU3 / Use Case 1 eval: is the gait workflow the official Mobilise-D pipeline?
 *
 * Runs UC1 (MS cohort) and UC2 (HA cohort) through CARP-DSP, then, in the same locked
 * environment, runs mobgap's `MobilisedPipelineUniversal` on the recording each imported and
 * compares five stages bit for bit (`scripts/eval/mobilised_equivalence.py`): gait sequences,
 * initial contacts, per-second parameters, walking bouts and aggregated DMOs.
 * Writes mobilised-equivalence.csv and mobilised-equivalence-numbers.tex (to the paper with -PpaperDir).
 *
 *   ./gradlew :carp.dsp.demo:evalMobilisedEquivalence -PpaperDir=../carp-dsp-sys-paper
 */
fun main()
{
    val home = DemoIo.projectRoot().resolve( "build/mobilised-equivalence" ).apply { deleteRecursively(); mkdirs() }
    val script = home.resolve( "mobilised_equivalence.py" )
    DemoIo.copyResource( "scripts/eval/mobilised_equivalence.py", script.toPath() )

    val cases = listOf( "uc1" to "workflows/mobgap-gait-analysis.yaml", "uc2" to "workflows/mobgap-gait-analysis-ha.yaml" )
    val results = cases.map { ( name, workflow ) -> equivalenceCase( home, script, name, workflow ) }

    val csv = DemoIo.evalResultsDir().resolve( "mobilised-equivalence.csv" )
    csv.writeText( results.first().readLines().first() + "\n" )
    results.forEach { csv.appendText( it.readLines().drop( 1 ).joinToString( "\n", postfix = "\n" ) ) }
    writeEquivalenceNumbers( csv )
}

private fun equivalenceCase( home: File, script: File, name: String, workflow: String ): File
{
    val work = DemoRun.freshResultsDir( home.resolve( name ).toPath() )
    val loaded = DemoRun.loadWorkflow( workflow, work )
    val executor = WorkflowExecutor.filesystem( ClasspathStepLibrary(), work )
    val prepared = executor.prepare( loaded.source, loaded.descriptor )
    val runId = UUID.randomUUID()
    val runRoot = MobgapScripts.runRoot( work, prepared.plan, runId ).toFile()
    MobgapScripts.stage( runRoot.toPath() )
    val report = executor.run( prepared, runId )
    check( report.status == ExecutionStatus.SUCCEEDED ) { "$name failed: " + report.issues.joinToString { it.message } }

    // The reference sees the recording the workflow imported: pass on import-data's selection flags.
    val importArgs = prepared.descriptor.steps.filterIsInstance<DefinedStepDescriptor>()
        .first { it.id == "import-data" }.let { ( it.task as CommandTaskDescriptor ).args }
    val selection = importArgs.zipWithNext().filter { ( flag, _ ) -> flag in RECORDING_FLAGS }.flatMap { listOf( it.first, it.second ) }

    // The same locked environment the run used, found as the run found it.
    val ref = prepared.plan.requiredEnvironmentRefs.values.filterIsInstance<PixiEnvironmentRef>().single()
    val locked = ref.copy( lockFile = ref.lockFile?.let { runRoot.resolve( it ).absolutePath } )
    val manifest = checkNotNull( EnvironmentStore.resolve( locked ) ).directory.resolve( "pixi.toml" ).toFile()

    val out = home.resolve( "$name.csv" )
    val command = listOf( "pixi", "run", "--manifest-path", manifest.absolutePath, "python", script.absolutePath,
        "--run-root", runRoot.absolutePath, "--output", out.absolutePath ) + selection
    val exit = ProcessBuilder( command ).directory( home ).inheritIO().start().waitFor()
    check( out.isFile ) { "Equivalence check for $name wrote no result (exit $exit)" }
    return out
}

private val RECORDING_FLAGS = setOf( "--cohort", "--participant-id", "--test", "--trial" )

private fun writeEquivalenceNumbers( csv: File )
{
    // cohort, pipeline, mobgap, stage, rows, identical, max_abs_diff
    val rows = csv.readLines().drop( 1 ).filter { it.isNotBlank() }.map { it.split( "," ) }
    val numbers = DemoIo.evalResultsDir().resolve( "mobilised-equivalence-numbers.tex" )
    numbers.writeText(
        buildString {
            appendLine( "% GENERATED by MobilisedEquivalenceEval - do not edit; run :carp.dsp.demo:evalMobilisedEquivalence" )
            fun macro( name: String, value: Any ) = appendLine( "\\newcommand{\\$name}{$value}" )
            macro( "MobilisedEqVersion", rows.first()[ 2 ] )
            macro( "MobilisedEqCohorts", rows.map { it[ 0 ] }.distinct().joinToString( ", " ) )
            macro( "MobilisedEqPipelines", rows.map { it[ 1 ].removePrefix( "MobilisedPipeline" ) }.distinct().joinToString( ", " ) )
            macro( "MobilisedEqStages", rows.map { it[ 3 ] }.distinct().size )
            macro( "MobilisedEqCompared", rows.size )
            macro( "MobilisedEqIdentical", rows.count { it[ 5 ] == "True" } )
        }
    )
    println( numbers.readText() )
    DemoIo.publishToPaper( numbers, "generated/mobilised-equivalence-numbers.tex" )
}
