#!/usr/bin/env python3
"""Generate fault-injected copies of the mobgap workflow for the error-detection eval.

Five fault classes (one fixture each):
  type-mismatch    consumer input declares a type that differs from the producer output
  missing-producer input references a step id that does not exist
  missing-output   input port name has no matching output on the (valid) producer step
  cycle            a back-edge is added so the dependency graph is no longer a DAG
  missing-env      a step references an environment id that is not defined

All five are structural faults CARP resolves at plan time. Run:
    python gen_injections.py            # writes ../workflows/injections/*.yaml
"""
from __future__ import annotations
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
BASE = HERE.parent.parent / "workflows" / "mobgap-gait-analysis.yaml"
OUT = HERE.parent.parent / "workflows" / "injections"

STEP_ANCHOR = '\n  - id: "'


def step_span(text: str, step_id: str) -> tuple[int, int]:
    """Return [start, end) character span of a single step block in the steps: list."""
    start = text.find(f'{STEP_ANCHOR}{step_id}"')
    if start < 0:
        raise ValueError(f"step '{step_id}' not found")
    start += 1  # skip the leading newline so the block begins at the two-space indent
    nxt = text.find(STEP_ANCHOR, start)
    end = len(text) if nxt < 0 else nxt + 1
    return start, end


def replace_in_step(text: str, step_id: str, old: str, new: str, expect: int = 1) -> str:
    """Replace `old`->`new` only within `step_id`'s block, asserting the hit count."""
    s, e = step_span(text, step_id)
    block = text[s:e]
    n = block.count(old)
    if n != expect:
        raise AssertionError(f"[{step_id}] expected {expect} of {old!r}, found {n}")
    return text[:s] + block.replace(old, new) + text[e:]


def gen_type_mismatch(base: str) -> str:
    # plot-aggregated-dmos consumes 'aggregated-dmos-csv' (producer: aggregate, csv).
    # Flip the consumer's declared type to json -> DEPENDENCY_TYPE_MISMATCH.
    return replace_in_step(
        base, "plot-aggregated-dmos",
        '        descriptor:\n          type: "csv"\n          format: "utf-8"\n          notes: "Final aggregated DMOs"',
        '        descriptor:\n          type: "json"\n          format: "utf-8"\n          notes: "Final aggregated DMOs"',
    )


def gen_missing_producer(base: str) -> str:
    # Point the plot-aggregated-dmos input at a step id that does not exist
    # -> DEPENDENCY_PRODUCER_NOT_FOUND.
    return replace_in_step(
        base, "plot-aggregated-dmos",
        '          stepId: "aggregate"',
        '          stepId: "aggregate-DOES-NOT-EXIST"',
    )


def gen_missing_output(base: str) -> str:
    # Rename the consumer input port so its name no longer matches any output of the
    # (valid) producer step -> DEPENDENCY_OUTPUT_NOT_FOUND. Producer resolution is by
    # name, so we mutate the input `id` (= port name), not the source stepId.
    return replace_in_step(
        base, "plot-aggregated-dmos",
        '      - id: "aggregated-dmos-csv"\n        descriptor:',
        '      - id: "aggregated-dmos-csv-UNDECLARED"\n        descriptor:',
    )


def gen_cycle(base: str) -> str:
    # Give the first step (import-data) an input sourced from the last data step
    # (aggregate). aggregate already transitively depends on import-data, so the added
    # back-edge closes a cycle -> WORKFLOW_CYCLE_DETECTED.
    inputs_block = (
        '    inputs:\n'
        '      - id: "aggregated-dmos-csv"\n'
        '        descriptor:\n'
        '          type: "csv"\n'
        '          format: "utf-8"\n'
        '          notes: "INJECTED back-edge to force a dependency cycle"\n'
        '        source:\n'
        '          type: "step-output"\n'
        '          stepId: "aggregate"\n'
        '          outputId: "aggregated-dmos-csv"\n'
    )
    # Insert immediately before import-data's outputs: block.
    return replace_in_step(
        base, "import-data",
        '    outputs:\n      - id: "imu-data-csv"',
        inputs_block + '    outputs:\n      - id: "imu-data-csv"',
    )


def gen_missing_env(base: str) -> str:
    # Repoint one step to an undefined environment -> MISSING_ENVIRONMENT_DEFINITION.
    return replace_in_step(
        base, "gsd",
        '    environmentId: "env-pixi"',
        '    environmentId: "env-does-not-exist"',
    )


GENERATORS = {
    "inj-type-mismatch": gen_type_mismatch,
    "inj-missing-producer": gen_missing_producer,
    "inj-missing-output": gen_missing_output,
    "inj-cycle": gen_cycle,
    "inj-missing-env": gen_missing_env,
}

HEADER = "# GENERATED by gen_injections.py - do not edit by hand.\n# Injected fault: {name}\n"


def main() -> int:
    base = BASE.read_text()
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in GENERATORS.items():
        out = fn(base)
        if out == base:
            raise AssertionError(f"{name}: no change applied")
        (OUT / f"{name}.yaml").write_text(HEADER.format(name=name) + out)
        print(f"wrote {name}.yaml  ({len(out) - len(base):+d} chars vs base)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
