#!/usr/bin/env python3
"""Aggregate the dependency-drift sweep across the whole dataset.

Reads drift-per-datapoint.csv (version x recording -> walking speed) and reports, for each
non-baseline version, how many recordings changed relative to the pinned baseline and by how
much. Writes drift-summary.txt, drift-summary.csv, and drift-table.tex into --out.

  python analyze_drift.py drift-per-datapoint.csv --out ../../eval_results
"""
import argparse
import csv
import pathlib
import statistics as st
from collections import defaultdict

PREFERRED_BASE = "0.10.0"  # the version the workflow was authored/pinned against, if present
TOL = 1e-9  # a recording "changes" if the DMO moves by more than this (mm/s scale is 1e-3)


def _vkey(v):
    """Sort key for a semantic-ish version string, e.g. '0.11.0' -> (0, 11, 0)."""
    return tuple(int(p) if p.isdigit() else 0 for p in v.split("."))


def load(path):
    ws = defaultdict(dict)
    with open(path) as f:
        for r in csv.DictReader(f):
            ws[r["datapoint"]][r["version"]] = float(r["walking_speed_mps"])
    return ws


def versions_of(ws):
    """Ordered versions present in the data, and the baseline to compare against."""
    vs = sorted({v for d in ws.values() for v in d}, key=_vkey)
    base = PREFERRED_BASE if PREFERRED_BASE in vs else vs[0]
    return vs, base


def summarise(ws):
    keys = list(ws)
    order, base = versions_of(ws)
    rows = []
    for v in order:
        if v == base:
            continue
        deltas = [ws[k][v] - ws[k][base] for k in keys]
        absd = [abs(d) for d in deltas]
        rel = [abs(ws[k][v] - ws[k][base]) / ws[k][base] * 100 for k in keys]
        changed = sum(1 for d in absd if d > TOL)
        rows.append({
            "version": v, "changed": changed, "total": len(keys),
            "rate": changed / len(keys), "mean_abs_mm": st.mean(absd) * 1000,
            "max_abs_mm": max(absd) * 1000, "mean_pct": st.mean(rel), "max_pct": max(rel),
        })
    return keys, rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", nargs="?", default="drift-per-datapoint.csv")
    ap.add_argument("--out", default=".")
    args = ap.parse_args()
    ws = load(args.src)
    order, base = versions_of(ws)
    keys, rows = summarise(ws)
    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    txt = [f"Dependency-drift sweep - walking speed across {len(order)} mobgap versions",
           f"Dataset: LabExample (INDIP), {len(keys)} recordings; baseline = v{base} (pinned)",
           f"A recording 'changes' if its walking speed moves by > {TOL} m/s.", ""]
    txt.append(f"  {'version':8}{'changed':>10}{'rate':>7}{'mean|d|mm/s':>13}{'max|d|mm/s':>12}{'max%':>8}")
    for r in rows:
        txt.append(f"  {r['version']:8}{r['changed']:>6}/{r['total']:<3}{r['rate']*100:>5.0f}%"
                   f"{r['mean_abs_mm']:>13.3f}{r['max_abs_mm']:>12.3f}{r['max_pct']:>8.2f}")
    ever = sum(1 for k in keys if len({round(ws[k][v], 9) for v in order}) > 1)
    txt += ["", f"Recordings that took >1 distinct value across {order[0]}->{order[-1]}: {ever}/{len(keys)}"]
    (out / "drift-summary.txt").write_text("\n".join(txt) + "\n")
    print("\n".join(txt))

    fieldnames = ["version", "changed", "total", "rate", "mean_abs_mm", "max_abs_mm", "mean_pct", "max_pct"]
    with open(out / "drift-summary.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(rows)

    tex = ["% GENERATED by analyze_drift.py - dependency-drift summary rows",
           "% cols: version & recordings changed & mean |d| (mm/s) & max |d| (mm/s) & max %"]
    for r in rows:
        tex.append(f"\\texttt{{{r['version']}}} & {r['changed']}/{r['total']} & "
                   f"{r['mean_abs_mm']:.2f} & {r['max_abs_mm']:.1f} & {r['max_pct']:.1f}\\% \\\\")
    (out / "drift-table.tex").write_text("\n".join(tex) + "\n")


if __name__ == "__main__":
    main()
